# frozen_string_literal: true

require "rails_helper"

# Phase 4n: MeCab 出力（実機で採取した IPA 辞書の分類）→ 骨格。
# で（場所）・と（共同）・だけ（限定）・か（疑問）・飲んで（接続助詞の で）を骨格に反映する。
RSpec.describe "骨格の拡張（Phase 4n）" do
  def skeleton_for(mecab_output)
    tokens = MeCabAdapter.call(mecab_output)
    result = KanbunBNFParser.new(tokens).parse
    result && SkeletonBuilder.call(result)
  end

  it "友と酒を飲んで語る → 与 友 飲む 酒 而 語る" do
    mecab = <<~MECAB
      友	名詞,一般,*,*,*,*,友,トモ,トモ
      と	助詞,並立助詞,*,*,*,*,と,ト,ト
      酒	名詞,一般,*,*,*,*,酒,サケ,サケ
      を	助詞,格助詞,一般,*,*,*,を,ヲ,ヲ
      飲ん	動詞,自立,*,*,五段・マ行,連用タ接続,飲む,ノン,ノン
      で	助詞,接続助詞,*,*,*,*,で,デ,デ
      語る	動詞,自立,*,*,五段・ラ行,基本形,語る,カタル,カタル
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "与 友 飲む 酒 而 語る"
  end

  it "兄は海で魚を釣る → 兄 釣る 魚 於 海" do
    mecab = <<~MECAB
      兄	名詞,一般,*,*,*,*,兄,アニ,アニ
      は	助詞,係助詞,*,*,*,*,は,ハ,ワ
      海	名詞,一般,*,*,*,*,海,ウミ,ウミ
      で	助詞,格助詞,一般,*,*,*,で,デ,デ
      魚	名詞,一般,*,*,*,*,魚,サカナ,サカナ
      を	助詞,格助詞,一般,*,*,*,を,ヲ,ヲ
      釣る	動詞,自立,*,*,五段・ラ行,基本形,釣る,ツル,ツル
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "兄 釣る 魚 於 海"
  end

  it "これは楽しくないか → これ 不 楽しい 乎" do
    mecab = <<~MECAB
      これ	名詞,代名詞,一般,*,*,*,これ,コレ,コレ
      は	助詞,係助詞,*,*,*,*,は,ハ,ワ
      楽しく	形容詞,自立,*,*,形容詞・イ段,連用テ接続,楽しい,タノシク,タノシク
      ない	助動詞,*,*,*,特殊・ナイ,基本形,ない,ナイ,ナイ
      か	助詞,副助詞／並立助詞／終助詞,*,*,*,*,か,カ,カ
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "これ 不 楽しい 乎"
  end

  it "ただ人だけが言葉を話す → 惟 人 話す 言葉" do
    mecab = <<~MECAB
      ただ	接続詞,*,*,*,*,*,ただ,タダ,タダ
      人	名詞,一般,*,*,*,*,人,ヒト,ヒト
      だけ	助詞,副助詞,*,*,*,*,だけ,ダケ,ダケ
      が	助詞,格助詞,一般,*,*,*,が,ガ,ガ
      言葉	名詞,一般,*,*,*,*,言葉,コトバ,コトバ
      を	助詞,格助詞,一般,*,*,*,を,ヲ,ヲ
      話す	動詞,自立,*,*,五段・サ行,基本形,話す,ハナス,ハナス
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "惟 人 話す 言葉"
  end

  it "りんごとみかんを買う → 買う りんごみかん" do
    mecab = <<~MECAB
      りんご	名詞,一般,*,*,*,*,りんご,リンゴ,リンゴ
      と	助詞,並立助詞,*,*,*,*,と,ト,ト
      みかん	名詞,一般,*,*,*,*,みかん,ミカン,ミカン
      を	助詞,格助詞,一般,*,*,*,を,ヲ,ヲ
      買う	動詞,自立,*,*,五段・ワ行促音便,基本形,買う,カウ,カウ
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "買う りんごみかん"
  end
end
