# frozen_string_literal: true

require "rails_helper"

# Phase 4x: 起点の「から」→ 自、可能の「できる」→ 能。
# MeCab の出力は IPA 辞書の分類を再現したもの（望見 は サ変接続名詞として扱われると仮定。実機の出力で要確認）。
RSpec.describe "起点・可能の骨格（Phase 4x）" do
  def skeleton_for(mecab_output)
    tokens = MeCabAdapter.call(mecab_output)
    result = KanbunBNFParser.new(tokens).parse
    result && SkeletonBuilder.call(result)
  end

  it "彼は鹿児島から来る → 彼 自 鹿児島 来る" do
    mecab = <<~MECAB
      彼\t名詞,代名詞,一般,*,*,*,彼,カレ,カレ
      は\t助詞,係助詞,*,*,*,*,は,ハ,ワ
      鹿児島\t名詞,固有名詞,地域,一般,*,*,鹿児島,カゴシマ,カゴシマ
      から\t助詞,格助詞,一般,*,*,*,から,カラ,カラ
      来る\t動詞,自立,*,*,カ変・来ル,基本形,来る,クル,クル
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "彼 自 鹿児島 来る"
  end

  it "私は鹿児島から閃光を望見できる → 私 自 鹿児島 能 望見 閃光" do
    mecab = <<~MECAB
      私\t名詞,代名詞,一般,*,*,*,私,ワタシ,ワタシ
      は\t助詞,係助詞,*,*,*,*,は,ハ,ワ
      鹿児島\t名詞,固有名詞,地域,一般,*,*,鹿児島,カゴシマ,カゴシマ
      から\t助詞,格助詞,一般,*,*,*,から,カラ,カラ
      閃光\t名詞,一般,*,*,*,*,閃光,センコウ,センコー
      を\t助詞,格助詞,一般,*,*,*,を,ヲ,ヲ
      望見\t名詞,サ変接続,*,*,*,*,望見,ボウケン,ボーケン
      できる\t動詞,自立,*,*,一段,基本形,できる,デキル,デキル
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "私 自 鹿児島 能 望見 閃光"
  end

  it "私は泳ぐことができる → 私 能 泳ぐ" do
    mecab = <<~MECAB
      私\t名詞,代名詞,一般,*,*,*,私,ワタシ,ワタシ
      は\t助詞,係助詞,*,*,*,*,は,ハ,ワ
      泳ぐ\t動詞,自立,*,*,五段・ガ行,基本形,泳ぐ,オヨグ,オヨグ
      こと\t名詞,非自立,一般,*,*,*,こと,コト,コト
      が\t助詞,格助詞,一般,*,*,*,が,ガ,ガ
      できる\t動詞,自立,*,*,一段,基本形,できる,デキル,デキル
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "私 能 泳ぐ"
  end

  it "彼は泳ぐことができない → 彼 不 能 泳ぐ" do
    mecab = <<~MECAB
      彼\t名詞,代名詞,一般,*,*,*,彼,カレ,カレ
      は\t助詞,係助詞,*,*,*,*,は,ハ,ワ
      泳ぐ\t動詞,自立,*,*,五段・ガ行,基本形,泳ぐ,オヨグ,オヨグ
      こと\t名詞,非自立,一般,*,*,*,こと,コト,コト
      が\t助詞,格助詞,一般,*,*,*,が,ガ,ガ
      でき\t動詞,自立,*,*,一段,未然形,できる,デキ,デキ
      ない\t助動詞,*,*,*,特殊・ナイ,基本形,ない,ナイ,ナイ
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "彼 不 能 泳ぐ"
  end

  it "理由の から（接続助詞）は起点にしない（骨格なし＝LLM に任せる）" do
    mecab = <<~MECAB
      雨\t名詞,一般,*,*,*,*,雨,アメ,アメ
      が\t助詞,格助詞,一般,*,*,*,が,ガ,ガ
      降る\t動詞,自立,*,*,五段・ラ行,基本形,降る,フル,フル
      から\t助詞,接続助詞,*,*,*,*,から,カラ,カラ
      行か\t動詞,自立,*,*,五段・カ行促音便,未然形,行く,イカ,イカ
      ない\t助動詞,*,*,*,特殊・ナイ,基本形,ない,ナイ,ナイ
      EOS
    MECAB
    expect(skeleton_for(mecab)).to be_nil
  end

  it "起点・可能のない文は従来どおり" do
    mecab = <<~MECAB
      犬\t名詞,一般,*,*,*,*,犬,イヌ,イヌ
      が\t助詞,格助詞,一般,*,*,*,が,ガ,ガ
      走る\t動詞,自立,*,*,五段・ラ行,基本形,走る,ハシル,ハシル
      EOS
    MECAB
    expect(skeleton_for(mecab)).to eq "犬 走る"
  end
end
